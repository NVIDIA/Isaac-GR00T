import asyncio
from dataclasses import dataclass
import datetime as dt
from datetime import datetime
import enum
import json
import os
from pathlib import Path
import subprocess
from typing import ClassVar
import xml.etree.ElementTree as ET

from groot.infra.ci import db, log, test
from groot.infra.ci.osmo_workflow_owner import OsmoWorkflowOwner

S3_KEY_PREFIX = "rws/ci/test_runs"
DEFAULT_TEST_OWNER = "cuonguyen"


class TestStatus(enum.Enum):
    PASSED = "passed"
    FAILED = "failed"
    SKIPPED = "skipped"


@dataclass
class TestRun:
    """An abstraction to represent a test run in the CI/CD pipeline."""

    test: test.Test
    status: TestStatus
    duration: int
    branch: str
    commit: str
    timestamp: datetime
    failure_log_tail: str | None = None
    gitlab_job_id: int | None = None
    osmo_workflow_name: str | None = None

    _db: ClassVar[db.Database] = db.Database()
    _logger: ClassVar = log.init(__name__)

    @classmethod
    def init_from_pytest_results(cls, junit_xml_path: Path) -> list["TestRun"]:
        """Parse JUnit XML file and convert to TestRun objects.

        Args:
            junit_xml_path: Path to the JUnit XML file generated by pytest

        Returns:
            List of TestRun objects
        """
        tree = ET.parse(junit_xml_path)
        root = tree.getroot()

        test_runs = []

        # Iterate through all test cases
        for testcase in root.iter("testcase"):
            # Extract test information
            classname = testcase.get("classname", "")
            name = testcase.get("name", "")
            duration = float(testcase.get("time", 0))

            # Construct full test nodeid (pytest format)
            nodeid = f"{classname}::{name}" if classname else name

            # Determine test status
            if testcase.find("failure") is not None or testcase.find("error") is not None:
                status = TestStatus.FAILED
            elif testcase.find("skipped") is not None:
                status = TestStatus.SKIPPED
            else:
                status = TestStatus.PASSED

            # Extract failure log for failed tests
            failure_log_tail = None
            if status == TestStatus.FAILED:
                _fe = testcase.find("failure")
                failure_elem = _fe if _fe is not None else testcase.find("error")
                if failure_elem is not None:
                    parts = [failure_elem.text or ""]
                    system_out = testcase.find("system-out")
                    if system_out is not None and system_out.text:
                        parts.append(system_out.text)
                    failure_log_tail = "\n".join(p for p in parts if p)

            # Create Test object
            test_ = test.Test(name=nodeid, owner=DEFAULT_TEST_OWNER, type=test.TestType.UNIT)

            _job_id_str = os.getenv("CI_JOB_ID", "")
            # Create TestRun object
            test_run = cls(
                test=test_,
                status=status,
                duration=int(duration),
                branch=os.getenv("CI_COMMIT_BRANCH", "unknown"),
                commit=os.getenv("CI_COMMIT_SHA", "unknown"),
                timestamp=datetime.now(dt.timezone.utc),
                gitlab_job_id=int(_job_id_str) if _job_id_str else None,
                failure_log_tail=failure_log_tail,
            )

            test_runs.append(test_run)

        return test_runs

    @classmethod
    def init_from_osmo_log(
        cls,
        log_json_path: Path,
        test_type: test.TestType = test.TestType.INTEGRATION,
        workflow_owners: list[OsmoWorkflowOwner] | None = None,
    ) -> list["TestRun"]:
        """Parse OSMO workflow log.json file and convert to TestRun objects.

        Args:
            log_json_path: Path to the log.json file generated by osmo_runner
            test_type: Type of test to assign to the created TestRun objects.
            workflow_owners: Optional owner metadata from the OSMO workflow list.

        Returns:
            List of TestRun objects
        """
        with open(log_json_path) as f:
            log_data = json.load(f)

        test_runs = []

        # Extract workflows from the integration section
        workflows = log_data.get("integration", {}).get("workflows", [])

        for workflow in workflows:
            # Extract workflow information
            name = workflow.get("name", "unknown")
            status_str = workflow.get("status", "UNKNOWN")
            start_time_str = workflow.get("start_time")
            end_time_str = workflow.get("end_time")

            # Calculate duration in seconds
            duration = 0
            if start_time_str and end_time_str:
                try:
                    start_time = datetime.strptime(start_time_str, "%Y-%m-%d %H:%M:%S").replace(
                        tzinfo=dt.timezone.utc
                    )
                    end_time = datetime.strptime(end_time_str, "%Y-%m-%d %H:%M:%S").replace(
                        tzinfo=dt.timezone.utc
                    )
                    duration = int((end_time - start_time).total_seconds())
                except ValueError:
                    duration = 0

            # Map OSMO status to TestStatus
            # COMPLETED (2) = workflow completed successfully
            if status_str == "COMPLETED":
                status = TestStatus.PASSED
            # All failure states map to FAILED
            elif status_str in (
                "FAILED_WF",  # OSMO indicated workflow failed (3)
                "FAILED_EXEC_TIMEOUT",  # Timeout during execution (4)
                "FAILED_SERVER_ERROR",  # Service internal error (5)
                "FAILED_PRECONDITION",  # Preconditions not met (8)
                "FAILED_SERVICE_TIMEOUT",  # Service timeout (9)
                "FAILED_CLI",  # CLI error (11)
                "FAILED_SUBMISSION",  # Submission failed (12)
            ):
                status = TestStatus.FAILED
            # Pending/running/waiting states map to SKIPPED (shouldn't appear in final log)
            elif status_str in (
                "PENDING",
                "RUNNING",
                "SUBMITTED",
                "WAITING",
                "FAILED_CANCELED",  # Canceled before execution (6)
                "FAILED_QUEUE_TIMEOUT",  # Queue timeout before execution (10)
            ):
                # SKIPPED: never ran (queued/running at capture time, or canceled/queue-timeout pre-execution)
                status = TestStatus.SKIPPED
            # Unknown/other statuses
            # SKIPPED: unknown/preempted status — workflow may have been preempted or had an unrecognized outcome
            else:
                status = TestStatus.SKIPPED

            # Create Test object for integration test
            owner = DEFAULT_TEST_OWNER
            for workflow_owner in workflow_owners or []:
                if workflow_owner.workflow_name == name:
                    owner = workflow_owner.as_test_owner()
                    break
            test_ = test.Test(name=name, owner=owner, type=test_type)

            # Fetch failure logs for failed runs
            failure_log_tail = None
            if status == TestStatus.FAILED:
                workflow_id = workflow.get("workflow_id")
                if workflow_id:
                    try:
                        result = subprocess.run(
                            ["osmo", "workflow", "logs", workflow_id],
                            check=False,
                            capture_output=True,
                            text=True,
                            timeout=60,
                        )
                        log_lines = (result.stdout or result.stderr or "").splitlines()
                        failure_log_tail = "\n".join(log_lines[-200:])
                    except Exception as e:  # noqa: BLE001
                        cls._logger.debug(f"Failed to fetch osmo logs for {workflow_id}: {e}")

            _job_id_str = os.getenv("CI_JOB_ID", "")
            # Create TestRun object
            test_run = cls(
                test=test_,
                status=status,
                duration=duration,
                branch=os.getenv("CI_COMMIT_BRANCH", "unknown"),
                commit=os.getenv("CI_COMMIT_SHA", "unknown"),
                timestamp=datetime.now(dt.timezone.utc),
                osmo_workflow_name=workflow.get("workflow_id"),
                gitlab_job_id=int(_job_id_str) if _job_id_str else None,
                failure_log_tail=failure_log_tail,
            )

            test_runs.append(test_run)

        return test_runs

    @classmethod
    def init_from_dict(cls, data: dict) -> "TestRun":
        """Create TestRun from dictionary."""
        test_ = test.Test(
            name=data["test"]["name"],
            owner=data["test"]["owner"],
            type=test.TestType[data["test"]["type"].upper()],
        )

        return cls(
            test=test_,
            status=TestStatus[data["status"].upper()],
            duration=data["duration"],
            branch=data["branch"],
            commit=data["commit"],
            timestamp=datetime.fromisoformat(data["timestamp"]),
            failure_log_tail=data.get("failure_log_tail"),
            gitlab_job_id=data.get("gitlab_job_id"),
            osmo_workflow_name=data.get("osmo_workflow_name"),
        )

    def get_canonical_name(self) -> str:
        """Get the database key representation (aka. canonical name) of the test run.

        Format: ``{test_canonical_name}_{commit}_{run_id}``. Including a per-attempt
        ``run_id`` (GitLab ``CI_JOB_ID`` in CI, a local timestamp otherwise) prevents
        retries of the same commit from overwriting each other in the database.
        """
        # CI_JOB_ID is unique per GitLab job attempt, so retries get distinct keys.
        # Fall back to the run timestamp when invoked outside CI.
        if self.gitlab_job_id is not None:
            run_id = str(self.gitlab_job_id)
        else:
            run_id = f"local-{int(self.timestamp.timestamp() * 1000)}"
        return f"{self.test.get_canonical_name()}_{self.commit}_{run_id}"

    async def async_persist(self) -> None:
        """Persist the test run to the database."""
        # Persist the test first
        await self.test.async_persist()
        # Persist the test run
        json_object = {
            "test": {
                "name": self.test.name,
                "owner": self.test.owner,
                "type": self.test.type.value,
                "state": self.test.state,
                "last_modified_by": self.test.last_modified_by,
            },
            "status": self.status.value,
            "duration": self.duration,
            "branch": self.branch,
            "commit": self.commit,
            "timestamp": self.timestamp.isoformat(),
            "failure_log_tail": self.failure_log_tail,
            "gitlab_job_id": self.gitlab_job_id,
            "osmo_workflow_name": self.osmo_workflow_name,
        }
        # Organize by test type: rws/ci/test_runs/{test_type}/{canonical_name}_{commit}_{run_id}.json
        await TestRun._db.async_write(
            f"{S3_KEY_PREFIX}/{self.test.type.value}/{self.get_canonical_name()}.json",
            json.dumps(json_object),
        )

    @classmethod
    async def get_all_paginated(
        cls,
        tests: list[test.Test],
        commits: list[str],
        branch: str | None = None,
        page: int = 1,
        page_size: int = 500,
    ) -> tuple[list["TestRun"], int]:
        """Fetch paginated test runs for given tests and commits (prefix-based filtering).

        Args:
            tests: List of Test objects to fetch runs for
            commits: List of commit SHAs to fetch runs for
            branch: Optional branch filter (applied post-read, not at key level)
            page: Page number (1-indexed)
            page_size: Number of test runs per page

        Returns:
            Tuple of (list of TestRun objects for the page, total count before branch filter)
        """
        db_ = cls._db

        test_types = {t.type.value for t in tests}
        commit_set = set(commits)
        cls._logger.info(f"Filtering by {len(tests)} tests and {len(commits)} commits")

        # List S3 keys using PREFIX for each test and filter by commit SHA at key level.
        # File format: rws/ci/test_runs/{test_type}/{canonical_name}_{commit_sha}_{run_id}.json
        # After listing with prefix rws/ci/test_runs/{test_type}/{canonical_name}_,
        # the remainder is {commit_sha}_{run_id}.json; the commit SHA is everything
        # before the first underscore.
        filtered_keys: list[str] = []

        for test_type in test_types:
            type_canonical_names = [
                t.get_canonical_name() for t in tests if t.type.value == test_type
            ]

            list_tasks = [
                db_.async_list(f"{S3_KEY_PREFIX}/{test_type}/{canonical_name}_")
                for canonical_name in type_canonical_names
            ]

            all_keys_per_test = await asyncio.gather(*list_tasks, return_exceptions=True)

            for i, keys_result in enumerate(all_keys_per_test):
                if isinstance(keys_result, Exception):
                    cls._logger.warning(f"Failed to list keys: {keys_result}")
                    continue

                canonical_name = type_canonical_names[i]
                prefix = f"{S3_KEY_PREFIX}/{test_type}/{canonical_name}_"
                for key in keys_result:
                    suffix = key[len(prefix) : -len(".json")]
                    commit_sha = suffix.split("_", 1)[0]
                    if commit_sha in commit_set:
                        filtered_keys.append(key)

        total_count = len(filtered_keys)
        cls._logger.info(
            f"Found {total_count} test run files matching commits after prefix filtering"
        )

        if not filtered_keys:
            cls._logger.warning("No test run files found!")
            return [], 0

        # Paginate at the key level (before reading S3)
        start_idx = (page - 1) * page_size
        end_idx = start_idx + page_size
        paginated_keys = filtered_keys[start_idx:end_idx]

        cls._logger.info(f"Reading {len(paginated_keys)} test run files for page {page}...")
        test_run_jsons = await asyncio.gather(
            *[db_.async_read(key) for key in paginated_keys], return_exceptions=True
        )

        test_runs = []
        errors = 0
        for test_run_json in test_run_jsons:
            if isinstance(test_run_json, Exception):
                errors += 1
                continue

            try:
                data = json.loads(test_run_json)

                # Post-filter by branch (stored in file content, not filename)
                if branch and data["branch"] != branch:
                    continue

                test_runs.append(cls.init_from_dict(data))
            except (json.JSONDecodeError, KeyError):
                errors += 1
                continue

        if errors > 0:
            cls._logger.warning(f"Skipped {errors} files due to read/parse errors")

        cls._logger.info(f"Successfully parsed {len(test_runs)} test runs")
        return test_runs, total_count
