"""Script to read test results and persist them to the database.

Supports two formats:
1. JUnit XML (pytest results)
2. OSMO workflow log.json (integration test results)

Usage:
    # For pytest results
    python -m groot.infra.ci.main.testdb --junit-xml path/to/junit.xml
    python -m groot.infra.ci.main.testdb --junit-xml junit.xml --main-branch-only

    # For OSMO workflow results
    python -m groot.infra.ci.main.testdb --osmo-log-json path/to/log.json
    python -m groot.infra.ci.main.testdb --osmo-log-json log.json --main-branch-only
"""

import asyncio
import os
from pathlib import Path
import sys

import tyro

from groot.infra.ci.osmo_workflow_owner_template import OsmoWorkflowOwnerTemplate
from groot.infra.ci.test import TestType
from groot.infra.ci.test_run import TestRun


async def _persist_all(
    test_runs: list[TestRun],
) -> list[tuple[int, TestRun | None, Exception | None]]:
    """Persist all test runs concurrently. Returns (index, test_run, error) for each."""
    results: list[tuple[int, TestRun | None, Exception | None]] = []

    async def persist_one(i: int, tr: TestRun) -> tuple[int, TestRun | None, Exception | None]:
        try:
            await tr.async_persist()
            return (i, tr, None)
        except Exception as e:
            return (i, tr, e)

    tasks = [persist_one(i, tr) for i, tr in enumerate(test_runs)]
    results = await asyncio.gather(*tasks)
    return results


def main(
    junit_xml: Path | None = None,
    osmo_log_json: Path | None = None,
    osmo_workflow_list_yaml: Path | None = None,
    main_branch_only: bool = False,
    test_type: TestType = TestType.INTEGRATION,
) -> None:
    """Read test results and persist to database.

    Args:
        junit_xml: Path to the JUnit XML file generated by pytest (e.g., junit.xml)
        osmo_log_json: Path to the log.json file generated by osmo_runner
        osmo_workflow_list_yaml: Optional rendered workflow list containing owner metadata.
        main_branch_only: If True, only persist when CI_COMMIT_BRANCH == CI_DEFAULT_BRANCH.
        test_type: Test type to assign to each parsed workflow (only used with --osmo-log-json).
    """
    if main_branch_only:
        commit_branch = os.environ.get("CI_COMMIT_BRANCH")
        default_branch = os.environ.get("CI_DEFAULT_BRANCH")
        if commit_branch != default_branch:
            print(
                f"Skipping persist: CI_COMMIT_BRANCH ({commit_branch}) != CI_DEFAULT_BRANCH ({default_branch})"
            )
            return

    # Validate input: exactly one of junit_xml or osmo_log_json must be provided
    if junit_xml and osmo_log_json:
        print("Error: Cannot specify both --junit-xml and --osmo-log-json", file=sys.stderr)
        sys.exit(1)
    if not junit_xml and not osmo_log_json:
        print("Error: Must specify either --junit-xml or --osmo-log-json", file=sys.stderr)
        sys.exit(1)

    # Handle JUnit XML (pytest results)
    if junit_xml:
        if not junit_xml.exists():
            print(f"Error: JUnit XML file not found: {junit_xml}", file=sys.stderr)
            sys.exit(1)

        print(f"Reading pytest results from: {junit_xml}")
        test_runs = TestRun.init_from_pytest_results(junit_xml)

    # Handle OSMO osmo_log_json (integration test results)
    else:  # osmo_log_json is set
        if not osmo_log_json.exists():
            print(f"Error: OSMO log.json file not found: {osmo_log_json}", file=sys.stderr)
            sys.exit(1)
        if osmo_workflow_list_yaml and not osmo_workflow_list_yaml.exists():
            print(
                f"Error: OSMO workflow list YAML file not found: {osmo_workflow_list_yaml}",
                file=sys.stderr,
            )
            sys.exit(1)

        print(f"Reading OSMO workflow results from: {osmo_log_json}")
        workflow_owners = (
            OsmoWorkflowOwnerTemplate.init_from_path(osmo_workflow_list_yaml).get_all()
            if osmo_workflow_list_yaml
            else None
        )
        test_runs = TestRun.init_from_osmo_log(
            osmo_log_json,
            test_type=test_type,
            workflow_owners=workflow_owners,
        )

    print(f"Found {len(test_runs)} test results")

    # Persist all test runs concurrently
    results = asyncio.run(_persist_all(test_runs))

    errors = 0
    for i, (_, test_run, error) in enumerate(sorted(results, key=lambda r: r[0]), 1):
        if error:
            print(
                f"[{i}/{len(test_runs)}] Error persisting {test_run.test.name}: {error}",
                file=sys.stderr,
            )
            errors += 1
        else:
            print(
                f"[{i}/{len(test_runs)}] Persisted: {test_run.test.name} ({test_run.status.value})"
            )

    if errors:
        sys.exit(1)
    print("✅ Test results persisted to database")


if __name__ == "__main__":
    tyro.cli(main)
